def _generate_canonical_bars(
    ticker: str,
    last_price: Decimal,
    count: int = 260,
) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    """
    Generates a deterministic 260-trading-day OHLCV bar series ending at last_price,
    and calculates all canonical technical indicator metrics using the technical engine.
    """
    if count < 20 or last_price <= Decimal("0"):
        # Truncated or empty series for suspended/delisted testing
        return [], {}

    seed = sum(ord(c) for c in ticker)
    base_price = float(last_price)
    raw_closes = [base_price]
    curr = base_price
    for i in range(1, count):
        step_factor = math.sin((seed + i * 17) % 360 * math.pi / 180.0) * 0.015
        curr = max(0.5, curr / (1.0 + step_factor))
        raw_closes.append(curr)
    raw_closes.reverse()

    end_date = datetime(2026, 10, 24, 16, 0, 0, tzinfo=timezone.utc)
    curr_date = end_date
    trading_dates = []
    while len(trading_dates) < count:
        if curr_date.weekday() < 5:
            trading_dates.append(curr_date)
        curr_date -= timedelta(days=1)
    trading_dates.reverse()

    closes: List[Decimal] = []
    highs: List[Decimal] = []
    lows: List[Decimal] = []
    bars: List[Dict[str, Any]] = []

    for i in range(count):
        c = Decimal(str(round(raw_closes[i], 2)))
        o = Decimal(str(round(raw_closes[i] * (1.0 - 0.002 * math.cos(i)), 2)))
        h = max(o, c) + Decimal(str(round(abs(raw_closes[i] * 0.008), 2)))
        lo = max(Decimal("0.01"), min(o, c) - Decimal(str(round(abs(raw_closes[i] * 0.008), 2))))
        vol = Decimal(str(int(1000000 + (seed * 1000 + i * 37000) % 5000000)))
        t_dt = trading_dates[i]
        closes.append(c)
        highs.append(h)
        lows.append(lo)
        bars.append({
            "timestamp": t_dt.isoformat(),
            "time_unix": int(t_dt.timestamp()),
            "open": o,
            "high": h,
            "low": lo,
            "close": c,
            "volume": vol,
            "is_final": True,
        })

    sma_20 = compute_sma(closes, 20)
    sma_50 = compute_sma(closes, 50)
    sma_100 = compute_sma(closes, 100)
    sma_200 = compute_sma(closes, 200)

    ema_20 = compute_ema(closes, 20)
    ema_50 = compute_ema(closes, 50)
    ema_200 = compute_ema(closes, 200)

    rsi_14 = compute_rsi(closes, 14)

    macd_res = compute_macd(closes, 12, 26, 9)
    macd_line = macd_res["macd"] if macd_res else None
    macd_signal = macd_res["signal"] if macd_res else None
    macd_hist = macd_res["histogram"] if macd_res else None

    bb_res = compute_bollinger_bands(closes, 20)
    bollinger_middle = bb_res["middle"] if bb_res else None
    bollinger_upper = bb_res["upper"] if bb_res else None
    bollinger_lower = bb_res["lower"] if bb_res else None
    bollinger_bandwidth = bb_res["bandwidth"] if bb_res else None
    bollinger_pct_b = bb_res["percent_b"] if bb_res else None

    atr_res = compute_atr(highs, lows, closes, 14)
    atr_14 = atr_res["atr"] if atr_res else None
    atr_pct = atr_res["atr_pct"] if atr_res else None

    momentum_5d = compute_momentum(closes, 5)
    momentum_20d = compute_momentum(closes, 20)
    momentum_60d = compute_momentum(closes, 60)
    momentum_252d = compute_momentum(closes, 252)

    historical_volatility_20d = compute_historical_volatility(closes, 20)

    hl_res = compute_52w_high_low(closes)
    high_52w = hl_res["high_52w"] if hl_res else None
    low_52w = hl_res["low_52w"] if hl_res else None
    price_to_52w_high = hl_res["pct_from_high"] if hl_res else None
    price_to_52w_low = hl_res["pct_from_low"] if hl_res else None

    golden_cross = (sma_50 > sma_200) if (sma_50 and sma_200) else None
    price_above_sma200 = (last_price > sma_200) if (last_price and sma_200) else None
    price_above_sma50 = (last_price > sma_50) if (last_price and sma_50) else None
    macd_crossover = (macd_line > macd_signal) if (macd_line and macd_signal) else None

    indicators = {
        "sma_20": sma_20,
        "sma_50": sma_50,
        "sma_100": sma_100,
        "sma_200": sma_200,
        "ema_20": ema_20,
        "ema_50": ema_50,
        "ema_200": ema_200,
        "rsi_14": rsi_14,
        "macd_line": macd_line,
        "macd_signal": macd_signal,
        "macd_hist": macd_hist,
        "bollinger_middle": bollinger_middle,
        "bollinger_upper": bollinger_upper,
        "bollinger_lower": bollinger_lower,
        "bollinger_bandwidth": bollinger_bandwidth,
        "bollinger_pct_b": bollinger_pct_b,
        "atr_14": atr_14,
        "atr_pct": atr_pct,
        "momentum_5d": momentum_5d,
        "momentum_20d": momentum_20d,
        "momentum_60d": momentum_60d,
        "momentum_252d": momentum_252d,
        "historical_volatility_20d": historical_volatility_20d,
        "high_52w": high_52w,
        "low_52w": low_52w,
        "price_to_52w_high": price_to_52w_high,
        "price_to_52w_low": price_to_52w_low,
        "golden_cross": golden_cross,
        "price_above_sma200": price_above_sma200,
        "price_above_sma50": price_above_sma50,
        "macd_crossover": macd_crossover,
    }
    return bars, indicators
