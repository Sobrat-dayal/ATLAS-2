# 5. ScreenerRepository Implementation
# =============================================================================
class ScreenerRepository:
    """Authoritative screener catalog and data access repository."""

    def __init__(self, records: Optional[List[ScreenerObservationRecord]] = None):
        self._universes: Dict[str, ScreenerUniverseDefinition] = {
            u.universe_id: u for u in CANONICAL_UNIVERSES
        }
        self._filters: Dict[str, ScreenerFilterDefinition] = {
            f.filter_id: f for f in CANONICAL_FILTERS
        }
        self._columns: Dict[str, ScreenerColumnDefinition] = {
            c.column_id: c for c in CANONICAL_COLUMNS
        }
        self._records: List[ScreenerObservationRecord] = (
            records if records is not None else _build_canonical_observation_catalog()
        )

    def get_universes(self) -> List[ScreenerUniverseDefinition]:
        return list(self._universes.values())

    def get_universe(self, universe_id: str) -> Optional[ScreenerUniverseDefinition]:
        return self._universes.get(universe_id.lower().strip())

    def get_filters(self) -> List[ScreenerFilterDefinition]:
        return list(self._filters.values())

    def get_filter(self, filter_id: str) -> Optional[ScreenerFilterDefinition]:
        return self._filters.get(filter_id.lower().strip())

    def get_columns(self) -> List[ScreenerColumnDefinition]:
        return list(self._columns.values())

    def get_column(self, column_id: str) -> Optional[ScreenerColumnDefinition]:
        return self._columns.get(column_id.lower().strip())

    def get_records(self) -> List[ScreenerObservationRecord]:
        return self._records
