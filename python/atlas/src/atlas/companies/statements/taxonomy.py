"""Canonical Accounting Concepts Taxonomy & Statement Hierarchy (Stage 82).

Defines:
- Canonical concept identifiers
- Display labels and descriptions
- Hierarchical structure (parent-child relationships and grouping levels)
- Display order
- Applicable statement types
- Sign and unit conventions
- Industry specializations (Industrial, Banking, Insurance)
"""

from typing import List, Optional

from pydantic import BaseModel

from atlas.companies.statements.enums import StatementType


class ConceptHierarchyNode(BaseModel):
    concept_id: str
    label: str
    statement_type: StatementType
    parent_id: Optional[str] = None
    hierarchy_level: int = 0
    display_order: int = 0
    is_group: bool = False
    is_total: bool = False
    normal_sign: str = "signed"  # "positive", "negative", "signed"
    unit_category: str = "currency"  # "currency", "shares", "currency_per_share", "percent"
    description: Optional[str] = None
    industry_sector: Optional[str] = None  # None for generic, "banking", "insurance"


