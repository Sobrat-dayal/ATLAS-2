def get_statement_hierarchy(statement_type: StatementType) -> List[ConceptHierarchyNode]:
    """Returns the ordered hierarchical nodes for a given statement type."""
    if statement_type == StatementType.INCOME_STATEMENT:
        return INCOME_STATEMENT_HIERARCHY
    elif statement_type == StatementType.BALANCE_SHEET:
        return BALANCE_SHEET_HIERARCHY
    elif statement_type == StatementType.CASH_FLOW_STATEMENT:
        return CASH_FLOW_HIERARCHY
    return []
