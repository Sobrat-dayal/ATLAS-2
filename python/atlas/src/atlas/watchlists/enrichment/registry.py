ENRICHMENT_COLUMN_MAP: Dict[str, EnrichmentColumnMetadata] = {
    col.column_id: col for col in ENRICHMENT_CATALOG
}


def get_enrichment_metadata(column_id: str) -> Optional[EnrichmentColumnMetadata]:
    """Retrieve metadata for an enrichment column, or None if not an enrichment column."""
    return ENRICHMENT_COLUMN_MAP.get(column_id)


def is_enrichment_column(column_id: str) -> bool:
    """Returns True if the column is an authorized Stage 79 enrichment column."""
    return column_id in ENRICHMENT_COLUMN_MAP


def list_enrichment_columns(
    category: Optional[EnrichmentCategory] = None,
) -> List[EnrichmentColumnMetadata]:
    """List all registered enrichment column specifications, optionally filtered by category."""
    if category is not None:
        return [c for c in ENRICHMENT_CATALOG if c.category == category]
    return list(ENRICHMENT_CATALOG)
