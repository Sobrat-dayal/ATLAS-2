"""Enumerations for ATLAS Command Language v1."""

from enum import StrEnum


class AtlasCommandSourceKind(StrEnum):
    """Source classification of the incoming command text."""

    SLASH = "slash"
    SHORTHAND = "shorthand"


class AtlasCommandParseStatus(StrEnum):
    """Parse and execution readiness status."""

    READY = "READY"
    INCOMPLETE = "INCOMPLETE"
    AMBIGUOUS = "AMBIGUOUS"
    INVALID = "INVALID"
    UNAVAILABLE = "UNAVAILABLE"


class AtlasCommandErrorCode(StrEnum):
    """Stable machine-readable error codes for command parsing."""

    COMMAND_TOO_LONG = "COMMAND_TOO_LONG"
    TOO_MANY_TOKENS = "TOO_MANY_TOKENS"
    TOKEN_TOO_LONG = "TOKEN_TOO_LONG"
    UNEXPECTED_TOKEN = "UNEXPECTED_TOKEN"
    UNTERMINATED_QUOTE = "UNTERMINATED_QUOTE"
    FORBIDDEN_SYNTAX = "FORBIDDEN_SYNTAX"
    CONTROL_CHARACTERS = "CONTROL_CHARACTERS"
    UNKNOWN_COMMAND = "UNKNOWN_COMMAND"
    UNKNOWN_MODULE = "UNKNOWN_MODULE"
    UNKNOWN_ACTION = "UNKNOWN_ACTION"
    UNKNOWN_PARAMETER = "UNKNOWN_PARAMETER"
    DUPLICATE_PARAMETER = "DUPLICATE_PARAMETER"
    INVALID_PARAMETER_VALUE = "INVALID_PARAMETER_VALUE"
    MISSING_TARGET = "MISSING_TARGET"
    TARGET_NOT_FOUND = "TARGET_NOT_FOUND"
    TARGET_AMBIGUOUS = "TARGET_AMBIGUOUS"
    TARGET_TYPE_MISMATCH = "TARGET_TYPE_MISMATCH"
    COMMAND_UNAVAILABLE = "COMMAND_UNAVAILABLE"
    COMMAND_FORBIDDEN = "COMMAND_FORBIDDEN"
    NOT_STRUCTURED_COMMAND = "NOT_STRUCTURED_COMMAND"
