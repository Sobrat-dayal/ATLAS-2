"""Settings for ATLAS Natural-Language Command Interpretation (Stage 48)."""

from typing import Optional

from pydantic import BaseModel, Field


class NaturalLanguageCommandSettings(BaseModel):
    """Configuration settings for the Natural-Language Command Interpreter."""

    enabled: bool = Field(
        default=True,
        description="Whether natural language interpretation is enabled.",
    )
    model_base_url: str = Field(
        default="",
        description="Base URL for the OpenAI-compatible model endpoint.",
    )
    model_name: str = Field(
        default="gpt-4o-mini",
        description="Name of the model to query for structured interpretation.",
    )
    model_api_key: Optional[str] = Field(
        default="",
        description="Server-side API key for the model provider.",
    )
    timeout_seconds: float = Field(
        default=10.0,
        description="Maximum request timeout in seconds.",
    )
    max_input_characters: int = Field(
        default=1000,
        description="Maximum length of user natural language input in characters.",
    )
    max_output_tokens: int = Field(
        default=256,
        description="Maximum tokens generated by the model.",
    )
    temperature: float = Field(
        default=0.0,
        description="Sampling temperature for deterministic classification.",
    )
    max_ambiguity_candidates: int = Field(
        default=10,
        description="Maximum disambiguation candidates returned on ambiguous targets.",
    )
    mock_mode: bool = Field(
        default=False,
        description="When True, uses deterministic mock interpretation instead of network call.",
    )
